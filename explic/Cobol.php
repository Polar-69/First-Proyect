            <h1 class="encabezado">Cobol:</h1>

            <p class="text-tl">En la creación de este lenguaje participó la comisión CODASYL, compuesta por fabricantes de ordenadores, usuarios y el Departamento de Defensa de Estados Unidos en mayo de 1959. La definición del lenguaje se completó en poco más de seis meses, siendo aprobada por la comisión en enero de 1960. El lenguaje COBOL fue diseñado inspirándose en el lenguaje Flow-Matic de la oficial Grace Hopper y el IBM COMTRAN de Bob Bemer, ya que ambos formaron parte de la comisión.</p>

            <p class="text-tl">Gracias a la ayuda de los usuarios COBOL evolucionó rápidamente y fue revisado de 1961 a 1965 para añadirle nuevas funcionalidades. En 1968 salió la primera versión ANSI del lenguaje, siendo revisada posteriormente en 1974 (COBOL ANS-74), 1985 (COBOL ANS-85, ampliado en 1989 con funciones matemáticas, finalizando el estándar actual más usado, conocido como COBOL-ANSI), y en 2002 (COBOL ANS-2002).</p>

            <p class="text-tl">El último estándar es el COBOL 2014 que entre otras, incluye una nueva característica que permite gestión dinámica de la memoria (OCCURS DYNAMIC).</p>

            <p class="text-tl">Existe una versión IBM Enterprise Cobol, actualizada regularmente y lanzada en 1991, usada en sistemas Host (Mainframe) bajo z/OS.</p>