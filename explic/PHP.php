            <h1 class="encabezado">PHP:</h1>

            <p class="text-tl">Fue originalmente diseñado en Perl, con base en la escritura de un grupo de CGI binarios escritos en el lenguaje C por el programador danés-canadiense Rasmus Lerdorf en el año 1994 para mostrar su currículum vítae y guardar ciertos datos, como la cantidad de tráfico que su página web recibía. El 8 de junio de 1995 fue publicado "Personal Home Page Tools" después de que Lerdorf lo combinara con su propio Form Interpreter para crear PHP/FI.</p>

            <p class="text-tl">Dos programadores israelíes del Technion, Zeev Suraski y Andi Gutmans, reescribieron el analizador sintáctico (parser, en inglés) en 1997 y crearon la base del PHP3, y cambiaron el nombre del lenguaje por PHP: Hypertext Preprocessor. Inmediatamente comenzaron experimentaciones públicas de PHP3, y se publicó oficialmente en junio de 1998. Para 1999, Suraski y Gutmans reescribieron el código de PHP, y produjeron lo que hoy se conoce como motor Zend. También fundaron Zend Technologies en Ramat Gan, Israel.</p>

            <p class="text-tl">En mayo del 2000, PHP 4 se lanzó bajo el poder del motor Zend 1.0. El 13 de julio de 2007 se anunció la suspensión del soporte y desarrollo de la versión 4 de PHP, y, a pesar de lo anunciado, se ha liberado una nueva versión con mejoras de seguridad, la 4.4.8, publicada el 13 de enero del 2008, y posteriormente la versión 4.4.9, publicada el 7 de agosto del 2008. Según esta noticia, se le dio soporte a fallos críticos hasta el 9 de agosto del 2008.</p>

            <p class="text-tl">El 13 de julio de 2004, se lanzó PHP 5, utilizando el motor Zend Engine 2.0 (o Zend Engine 2). Incluye todas las ventajas que provee el nuevo Zend Engine 2, como:</p>

            <ul class="list-lp">

                <li>Mejor soporte para la programación orientada a objetos, que en versiones anteriores era extremadamente rudimentario.</li>
                
                <li>Mejoras de rendimiento</li>
                
                <li>Mejor soporte para MySQL con extensión completamente reescrita</li>
                
                <li>Mejor soporte a XML (XPath, DOM, etc.)</li>
                
                <li>Soporte nativo para SQLite</li>
                
                <li>Soporte integrado para SOAP</li>
                
                <li>Iteradores de datos</li>
                
                <li>Manejo de excepciones</li>
                
                <li>Mejoras con la implementación con Oracle</li>

            </ul>