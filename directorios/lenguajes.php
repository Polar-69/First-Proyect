            <h2 class="text-tl">¿Que es un lenguaje de programación?</h2>
            
            <p class="text-tl">Es un lenguaje formal que, mediante una serie de instrucciones, le permite a un programador escribir un conjunto de órdenes, 
            acciones consecutivas, datos y algoritmos para, de esa forma, crear programas que controlen el comportamiento físico y 
            lógico de una máquina. </p>
            
            <p class="text-tl">Mediante este lenguaje se comunican el programador y la máquina, permitiendo especificar, de forma precisa, aspectos como:</p>
            
            <ul class="list-lp">
                <li>cuáles datos debe operar un software específico.</li>
                <br>
                <li>cómo deben ser almacenados o transmitidos esos datos.</li>
                <br>
                <li>las acciones que debe tomar el software dependiendo de las circunstancias variables.</li>
                <br>
            </ul>

            <p class="text-tl"></p>

            <p class="text-tl">Es importante recalcar que existe el error común de usar como sinónimos el lenguaje de programación 
            y el lenguaje informático, pero ¿por qué no debemos confundirlos?</p>  

            <p class="text-tl">Pues, es debido a que el lenguaje de programación obedece a un conjunto de reglas que permiten expresar 
            las instrucciones que serán interpretadas por el programador. Y el lenguaje informático comprende otros 
            lenguajes que dan formato a un texto pero no son programación en sí mismos.</p>  

            <p class="text-tl">Entonces, no todos los lenguajes informáticos son de programación, pero todos los lenguajes de 
            programación son a la vez informáticos.</p> 
            
