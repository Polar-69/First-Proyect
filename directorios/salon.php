                        en tiempo real sobre una base de datos. Rasmus Lerdorf hablando sobre seguridad con desarrolladores 
                        en una conferencia en 2007. Como no existía una herramienta de interfaz con las bases de datos, creó 
                        un conjunto de etiquetas adicionales para insertar dentro de los códigos HTML de las propias páginas, 
                        reemplazando los CGI en Perl. Cuando el producto estuvo maduro, si bien Lerdorf había creado la interfaz 
                        con la base de datos MySQL, otros programadores crearon conectividad con Oracle y Sybase. Así cristalizó 
                        la idea de lanzar el PHP como una herramienta de software libre lo que llevó a que, con el aporte de la 
                        comunidad mundial, sea una herramienta de suma utilidad. Como el propio Lerdorf indica: "Yo solo puedo 
                        ayudarme a mí. Si todo el mundo usa el código que he escrito, con seguridad obtendré algo de él".</p>
                
